#!/bin/bash
# Builds and signs Silk.app.
#
#   scripts/build-app.sh            release → build/Silk.app        (dev.jensderond.silk)
#   scripts/build-app.sh --debug    debug   → build/Silk Debug.app  (dev.jensderond.silk.debug, "Silk Debug")
#
# Layout:
#   Contents/MacOS/Silk                 the SilkApp product, renamed
#   Contents/Resources/bin/silk         the CLI (not in MacOS/: "silk" and "Silk" collide on case-insensitive APFS)
#   Contents/Resources/*.bundle         SwiftPM resource bundles; Bundle.module looks in Bundle.main.resourceURL
#   Contents/Resources/AppIcon.icns     generated by scripts/make-icon.swift (committed)
#   Contents/Info.plist                 Resources/Info.plist + VERSION + git commit count/hash
#
# Signing identity: $SILK_SIGN_IDENTITY, else a default from the keychain, else ad-hoc. Release builds default to
# the first "Developer ID Application" identity (distributable, notarized by scripts/release.sh), debug builds to
# "Apple Development: Jens de Rond (799QBY4RBJ)". Hardened runtime, Resources/Silk.entitlements. A stable identity matters: macOS keys the Accessibility grant to
# it, so ad-hoc builds lose the grant on every rebuild.
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$PWD"

CONFIGURATION=release
if [[ "${1:-}" == "--debug" ]]; then
    CONFIGURATION=debug
elif [[ $# -gt 0 ]]; then
    echo "usage: $0 [--debug]" >&2
    exit 2
fi

if [[ "$CONFIGURATION" == release ]]; then
    BUNDLE_ID=dev.jensderond.silk
    BUNDLE_NAME=Silk
else
    BUNDLE_ID=dev.jensderond.silk.debug
    BUNDLE_NAME="Silk Debug"
fi
APP="$ROOT/build/$BUNDLE_NAME.app"

VERSION="$(tr -d '[:space:]' < VERSION)"
BUILD_NUMBER="$(git rev-list --count HEAD 2>/dev/null || echo 0)"
GIT_COMMIT="$(git rev-parse HEAD 2>/dev/null || echo SNAPSHOT)"

echo "==> Building $BUNDLE_NAME $VERSION ($BUILD_NUMBER, $CONFIGURATION)"
swift build -c "$CONFIGURATION" --product SilkApp
swift build -c "$CONFIGURATION" --product silk
BIN="$(swift build -c "$CONFIGURATION" --show-bin-path)"

echo "==> Assembling $APP"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/bin"
cp "$BIN/SilkApp" "$APP/Contents/MacOS/Silk"
cp "$BIN/silk" "$APP/Contents/Resources/bin/silk"
cp Resources/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"
shopt -s nullglob
for bundle in "$BIN"/*.bundle; do
    case "$(basename "$bundle")" in
        *Tests.bundle) ;; # test fixtures
        *) cp -R "$bundle" "$APP/Contents/Resources/" ;;
    esac
done
shopt -u nullglob

PLIST="$APP/Contents/Info.plist"
cp Resources/Info.plist "$PLIST"
plutil -replace CFBundleIdentifier -string "$BUNDLE_ID" "$PLIST"
plutil -replace CFBundleName -string "$BUNDLE_NAME" "$PLIST"
plutil -replace CFBundleDisplayName -string "$BUNDLE_NAME" "$PLIST"
plutil -replace CFBundleShortVersionString -string "$VERSION" "$PLIST"
plutil -replace CFBundleVersion -string "$BUILD_NUMBER" "$PLIST"
plutil -replace SilkGitCommit -string "$GIT_COMMIT" "$PLIST"
plutil -lint -s "$PLIST"
printf 'APPL????' > "$APP/Contents/PkgInfo"

IDENTITY="${SILK_SIGN_IDENTITY:-}"
if [[ -z "$IDENTITY" ]]; then
    IDENTITIES="$(security find-identity -v -p codesigning)"
    if [[ "$CONFIGURATION" == release ]]; then
        IDENTITY="$(awk -F '"' '/"Developer ID Application: / && !found { print $2; found = 1 }' <<< "$IDENTITIES")"
    elif grep -qF '"Apple Development: Jens de Rond (799QBY4RBJ)"' <<< "$IDENTITIES"; then
        IDENTITY="Apple Development: Jens de Rond (799QBY4RBJ)"
    fi
fi
if [[ -z "$IDENTITY" || "$IDENTITY" == "-" ]]; then
    IDENTITY="-"
    echo "warning: no signing identity found; signing ad-hoc. macOS will drop the Accessibility permission on every rebuild." >&2
    echo "         Set SILK_SIGN_IDENTITY to a codesigning identity from 'security find-identity -v -p codesigning'." >&2
fi

# Notarization requires a secure timestamp; other builds skip the round trip to Apple's timestamp server.
TIMESTAMP=--timestamp=none
if [[ "$IDENTITY" == "Developer ID Application: "* ]]; then
    TIMESTAMP=--timestamp
fi

echo "==> Signing with: $([[ "$IDENTITY" == "-" ]] && echo ad-hoc || echo "$IDENTITY")"
# Inside-out: the CLI is nested code and must carry its own signature before the bundle is sealed.
codesign --force "$TIMESTAMP" --options runtime --identifier "$BUNDLE_ID.cli" --sign "$IDENTITY" \
    "$APP/Contents/Resources/bin/silk"
codesign --force "$TIMESTAMP" --options runtime --entitlements Resources/Silk.entitlements --sign "$IDENTITY" "$APP"
codesign --verify --deep --strict "$APP"

echo "==> Built $APP"
